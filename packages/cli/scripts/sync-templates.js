/**
 * In pre-commit mode, check if any staged files touch source directories.
 * If not, skip sync entirely for fast commits.
 */
function shouldSyncForPreCommit() {
	try {
		const staged = execSync("git diff --cached --name-only", {
			cwd: ROOT,
			encoding: "utf-8",
		});
		const sourceDirPattern =
			/^(scripts\/|apps\/|packages\/(db|config|ui|jobs|opencode)\/|turbo\.json|docker-compose(\.override)?\.yml|pnpm-workspace\.yaml|package\.json)/;
		return staged.split("\n").some((f) => sourceDirPattern.test(f));
	} catch {
		return false;
	}
}

/**
 * Sync pnpm.overrides from the monorepo root package.json into the
 * hand-authored scaffold root package.json template. The template file is
 * template-only (different scripts, naming, onlyBuiltDependencies), but its
 * security overrides must mirror the monorepo's single source of truth.
 * @returns {{ action: string, file: string } | null}
 */
function syncRootOverrides() {
	const srcPath = path.join(ROOT, "package.json");
	const destPath = path.join(TEMPLATES, "base-project/package.json");

	const rootOverrides = JSON.parse(fs.readFileSync(srcPath, "utf-8")).pnpm
		?.overrides;
	const templatePkg = JSON.parse(fs.readFileSync(destPath, "utf-8"));

	if (
		JSON.stringify(templatePkg.pnpm?.overrides ?? null) ===
		JSON.stringify(rootOverrides ?? null)
	) {
		return null;
	}

	if (!CHECK_MODE) {
		templatePkg.pnpm = { ...templatePkg.pnpm, overrides: rootOverrides };
		fs.writeFileSync(destPath, `${JSON.stringify(templatePkg, null, "\t")}\n`);
	}

	return { action: "updated", file: "base-project/package.json (overrides)" };
}

function main() {
	// Pre-commit: skip sync if no relevant files are staged
	if (PRE_COMMIT_MODE && !shouldSyncForPreCommit()) {
		process.exit(0);
	}

	console.log(
		CHECK_MODE
			? "🔍 Checking template drift...\n"
			: "🔄 Syncing templates from monorepo source...\n",
	);

	const allChanges = [];

	// Sync directory mappings
	for (const mapping of SYNC_DIRS) {
		const changes = syncDirectory(mapping);
		allChanges.push(...changes);
	}

	// Sync individual file mappings
	for (const mapping of SYNC_FILES) {
		const srcPath = path.join(ROOT, mapping.src);
		const destPath = path.join(TEMPLATES, mapping.dest);

		if (isTemplateOnly(mapping.dest)) continue;

		const change = syncFile(srcPath, destPath, mapping.dest);
		if (change) allChanges.push(change);
	}

	// Sync pnpm.overrides from monorepo root into scaffold root template
	const overridesChange = syncRootOverrides();
	if (overridesChange) allChanges.push(overridesChange);

	// Generate template-only files from source data (package.json, .gitignore, biome.json)
	// These files are never synced from source — they're computed from it.
	for (const { dest, generate } of GENERATORS) {
		const content = generate();
		const destPath = path.join(TEMPLATES, dest);

		if (CHECK_MODE) {
			if (!fs.existsSync(destPath)) {
				allChanges.push({ action: "created", file: `GENERATED: ${dest}` });
			} else {
				const existing = fs.readFileSync(destPath, "utf-8");
				if (existing !== content) {
					allChanges.push({ action: "updated", file: `GENERATED: ${dest}` });
				}
			}
		} else {
			fs.mkdirSync(path.dirname(destPath), { recursive: true });
			const existed = fs.existsSync(destPath);
			fs.writeFileSync(destPath, content);
			allChanges.push({
				action: existed ? "updated" : "created",
				file: `GENERATED: ${dest}`,
			});
		}
	}

	// Report results
	if (allChanges.length === 0) {
		validateTemplateMigration();
		console.log("✅ Templates are in sync with monorepo source.\n");
		process.exit(0);
	}

	const created = allChanges.filter((c) => c.action === "created");
	const updated = allChanges.filter((c) => c.action === "updated");
	const deleted = allChanges.filter((c) => c.action === "deleted");

	if (CHECK_MODE) {
		console.log(
			`❌ Template drift detected: ${allChanges.length} file(s) would change.\n`,
		);
	} else {
		console.log(`📦 Synced ${allChanges.length} file(s):\n`);
	}

	if (created.length > 0) {
		console.log(`  Created (${created.length}):`);
		for (const c of created) console.log(`    + ${c.file}`);
	}
	if (updated.length > 0) {
		console.log(`  Updated (${updated.length}):`);
		for (const c of updated) console.log(`    ~ ${c.file}`);
	}
	if (deleted.length > 0) {
		console.log(`  Deleted (${deleted.length}):`);
		for (const c of deleted) console.log(`    - ${c.file}`);
	}

	console.log("");
	validateTemplateMigration();

	if (CHECK_MODE) {
		process.exit(1);
	}

	// Pre-commit: stage synced template files
	if (PRE_COMMIT_MODE) {
		execSync("git add packages/cli/templates/", { cwd: ROOT });
	}
}

main();
